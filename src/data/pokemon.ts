export const getEffectiveness = (attackerType: PokemonType, defenderTypes: PokemonType[]): number => {
  const { TYPE_CHART } = require('./types');
  let multiplier = 1.0;

  for (const defType of defenderTypes) {
    const mod = TYPE_CHART[attackerType]?.[defType];
    if (mod !== undefined) {
      multiplier *= mod;
    }
  }

  return multiplier;
};
